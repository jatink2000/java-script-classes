// general rules of a variables : 
// 1. variables name can start with letter or underscore (_). 
        // _groot=47
        // groot=46
        // document.writeln(_groot)
        // document.writeln(groot)

// 2. variables name cannot start with number . 
        // 1groot=48   
        // g2ro5ot6=48 

// 3. variables name cannot contain any symbol only $ symbol is used to create the variable . 
        // gr$oot=48

// 4. variables name are case senstive . 
        // groot=48
        // document.writeln(groot)


// 5. variables name cannot contain extra space .
        // groot academy=47




